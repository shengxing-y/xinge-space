"""Build the existing browser entry points from shared, dependency-free sources.

python build_assets.py          # write bundles
python build_assets.py --check  # verify checked-in bundles without writing
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def text(name):
    return (ROOT / name).read_text(encoding='utf-8').rstrip() + '\n'


def bundles():
    sky = "'use strict';\n/* Generated by build_assets.py; edit src/sky-renderer.js or the source modules. */\n"
    for symbol, name in [('SkyCatalog', 'sky-catalog.js'), ('SkyAstronomy', 'sky-astronomy.js')]:
        sky += f'if (!globalThis.{symbol}) {{\n' + text(name) + '}\n'
    sky += text('sky-names.js')
    sky += text('src/star-identify.js')
    sky += text('src/theme-policy.js')
    sky += '\n/* SKY_RENDERER_START */\n' + text('src/sky-renderer.js')
    common = text('src/activity.js') + text('src/reader.js')
    header = '/* Generated by build_assets.py; edit src/ files, not this bundle. */\n'
    return {
        'sky.js': sky,
        'app.js': header + common + text('src/app.js'),
        'static_app.js': header + common + text('src/static_app.js'),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, content in bundles().items():
        target = ROOT / name
        if args.check:
            if not target.exists() or target.read_text(encoding='utf-8') != content:
                stale.append(name)
        else:
            target.write_text(content, encoding='utf-8')
    if stale:
        raise SystemExit('Stale bundles: ' + ', '.join(stale))
    print('PASS: browser bundles match shared sources' if args.check else 'Built sky.js, app.js and static_app.js')


if __name__ == '__main__':
    main()
